#!/usr/bin/env node
// Puts built web editions on the VPS and writes the web server config for them.
//
//   RYKERSOFT_VPS=root@<vps> node web/apps/deploy.mjs              upload every built app, write config
//   RYKERSOFT_VPS=root@<vps> node web/apps/deploy.mjs wordplay     upload only these ids, write config
//   RYKERSOFT_VPS=root@<vps> node web/apps/deploy.mjs --cert       also request or extend the certificate
//   RYKERSOFT_VPS=root@<vps> node web/apps/deploy.mjs --config     write config only, upload nothing
//
// RYKERSOFT_VPS_KEY names the SSH key file when the default key is not the right one.
// The config always covers every app in apps.json. HTTPS is switched on once the certificate
// exists; until then each app answers only on the VPS's own loopback check port.
//
// An app with a "service" in apps.json also gets its bundled server (out-services/<id>/server.mjs)
// installed as the systemd unit rykersoft-app-<id>, listening on loopback only. Secrets, if a
// service ever needs any, go in /etc/rykersoft-apps/<id>.env on the VPS, never in this repository.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(here, 'apps.json'), 'utf8'));
const HOST = process.env.RYKERSOFT_VPS;
if (!HOST) fail('Set RYKERSOFT_VPS, for example root@<vps>.');
const KEY = process.env.RYKERSOFT_VPS_KEY;
const SSH = ['-o', 'BatchMode=yes', ...(KEY ? ['-o', 'IdentitiesOnly=yes', '-i', KEY] : [])];

const WEB_ROOT = '/var/www/rykersoft-apps';
const SITE = '/etc/nginx/sites-available/rykersoft-apps';
const SNIPPET = '/etc/nginx/snippets/rykersoft-app-static.conf';
const CERT_NAME = 'rykersoft-apps';
const CERT_DIR = `/etc/letsencrypt/live/${CERT_NAME}`;
const CHECK_PORT = 8431;
const SERVICE_ROOT = '/opt/rykersoft-apps';
const SERVICE_USER = 'rykersoft-apps';

const args = process.argv.slice(2);
const wantCert = args.includes('--cert');
const configOnly = args.includes('--config');
const ids = args.filter((a) => !a.startsWith('--'));
const unknown = ids.filter((id) => !manifest.apps.some((a) => a.id === id));
if (unknown.length) fail(`Not in apps.json: ${unknown.join(', ')}`);
const hostOf = (app) => `${app.id}.${manifest.domain}`;

function fail(message) {
  console.error(message);
  process.exit(1);
}

function local(cmd, cmdArgs, input) {
  const r = spawnSync(cmd, cmdArgs, { encoding: 'utf8', input, maxBuffer: 64 << 20 });
  if (r.status !== 0) throw new Error(`${cmd} failed\n${(r.stdout || '').slice(-2000)}\n${(r.stderr || '').slice(-2000)}`);
  return r.stdout;
}
const remote = (script, input) => local('ssh', [...SSH, HOST, script], input);

// Shared rules for every app. Nothing is cached without revalidation: built files are not all
// content-hashed (The Guile Family ships plain names), and service workers must update promptly.
const snippet = `# Generated by web/apps/deploy.mjs in github.com/rykergrey/RykerSoft. Edit there, not here.
index index.html;
gzip_types text/css application/javascript text/javascript application/json image/svg+xml application/wasm application/manifest+json;
add_header Cache-Control "no-cache" always;
add_header X-Content-Type-Options nosniff always;
add_header Referrer-Policy strict-origin-when-cross-origin always;
add_header Content-Security-Policy "frame-ancestors 'self'" always;
location / { try_files $uri $uri/ =404; }
location ~ \\.webmanifest$ { types { } default_type application/manifest+json; }
location ~ \\.mjs$ { types { } default_type text/javascript; }
`;

function siteConfig(https) {
  const names = manifest.apps.map(hostOf).join(' ');
  const blocks = manifest.apps.map((app) => {
    const proxies = (app.proxy || []).map((p) => `
    location ${p.path} {
        client_max_body_size ${p.maxBody || '1m'};
        proxy_pass ${p.upstream};
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;${p.websocket ? `
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $rykersoft_app_connection;` : ''}
        proxy_read_timeout ${p.readTimeout || (p.websocket ? '3600s' : '60s')};
        proxy_buffering off;
        add_header X-Content-Type-Options nosniff always;
    }`).join('');
    const tls = https ? `
    listen 443 ssl;
    http2 on;
    ssl_certificate ${CERT_DIR}/fullchain.pem;
    ssl_certificate_key ${CERT_DIR}/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;` : '';
    return `
server {
    server_name ${hostOf(app)};
    listen 127.0.0.1:${CHECK_PORT};${tls}
    root ${WEB_ROOT}/${app.id};
    include ${SNIPPET};${proxies}
}`;
  }).join('\n');
  return `# RykerSoft web editions: one address per app, each with its own browser storage.
# Generated by web/apps/deploy.mjs in github.com/rykergrey/RykerSoft from web/apps/apps.json.
# Edit there, not here. HTTPS: ${https ? 'on' : 'off until the certificate exists (deploy.mjs --cert)'}.

# Live connections (multiplayer rooms) ask to be upgraded from HTTP to a WebSocket.
map $http_upgrade $rykersoft_app_connection {
    default upgrade;
    ''      close;
}

# Plain HTTP only answers certificate challenges, then sends browsers to HTTPS.
server {
    listen 80;
    server_name ${names};
    location /.well-known/acme-challenge/ { root /var/www/certbot; }
    location / { return 301 https://$host$request_uri; }
}
${blocks}
`;
}

function writeConfig() {
  const https = remote(`test -f ${CERT_DIR}/fullchain.pem && echo yes || echo no`).trim() === 'yes';
  // Install both files, test, and put the previous ones back if the test fails.
  remote(`cat > ${SNIPPET}.new`, snippet);
  remote(`cat > ${SITE}.new`, siteConfig(https));
  const out = remote(`set -e
for f in ${SNIPPET} ${SITE}; do [ -f "$f" ] && cp -p "$f" "$f.prev" || rm -f "$f.prev"; mv "$f.new" "$f"; done
ln -sfn ${SITE} /etc/nginx/sites-enabled/rykersoft-apps
if nginx -t 2>/tmp/rykersoft-apps-nginx.log; then systemctl reload nginx; echo ok
else
  for f in ${SNIPPET} ${SITE}; do if [ -f "$f.prev" ]; then mv "$f.prev" "$f"; else rm -f "$f"; fi; done
  [ -f ${SITE} ] || rm -f /etc/nginx/sites-enabled/rykersoft-apps
  cat /tmp/rykersoft-apps-nginx.log; echo failed
fi`);
  if (!out.trim().endsWith('ok')) throw new Error(`The web server rejected the new config; the previous one is back in place.\n${out}`);
  console.log(`config           written, HTTPS ${https ? 'on' : 'off'}`);
  return https;
}

// Installs or updates one app's server. The unit has no access to the rest of the machine:
// its own user, a read-only system, no home folders, and one writable folder for its data.
function deployService(app) {
  const built = path.join(here, 'out-services', app.id, 'server.mjs');
  if (!fs.existsSync(built)) {
    console.log(`${app.id.padEnd(16)} service not built, skipped`);
    return;
  }
  const s = app.service;
  const unitName = `rykersoft-app-${app.id}`;
  const dir = `${SERVICE_ROOT}/${app.id}`;
  const environment = Object.entries({ NODE_ENV: 'production', HOST: '127.0.0.1', PORT: String(s.port), TRUST_PROXY: '1', DATA_DIR: `/var/lib/rykersoft-apps/${app.id}`, ...(s.env || {}) })
    .map(([k, v]) => `Environment=${k}=${v}`).join('\n');
  const unit = `# Generated by web/apps/deploy.mjs in github.com/rykergrey/RykerSoft. Edit apps.json there, not this file.
[Unit]
Description=RykerSoft web edition service: ${app.id}
After=network-online.target

[Service]
User=${SERVICE_USER}
Group=${SERVICE_USER}
WorkingDirectory=${dir}
${environment}
EnvironmentFile=-/etc/rykersoft-apps/${app.id}.env
ExecStart=/usr/bin/node ${dir}/server.mjs
Restart=on-failure
RestartSec=3
MemoryMax=${s.memoryMax || '300M'}
StateDirectory=rykersoft-apps/${app.id}
StateDirectoryMode=0750
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
UMask=0077

[Install]
WantedBy=multi-user.target
`;
  remote(`id ${SERVICE_USER} >/dev/null 2>&1 || useradd --system --home /var/lib/rykersoft-apps --shell /usr/sbin/nologin ${SERVICE_USER}
mkdir -p ${dir} /etc/rykersoft-apps && chmod 750 /etc/rykersoft-apps`);
  local('rsync', ['-az', '-e', `ssh ${SSH.join(' ')}`, built, path.join(path.dirname(built), 'service.json'), `${HOST}:${dir}/`]);
  remote(`cat > /etc/systemd/system/${unitName}.service`, unit);
  const state = remote(`chown -R root:${SERVICE_USER} ${dir} && chmod -R u=rwX,g=rX,o= ${dir}
systemctl daemon-reload && systemctl enable --quiet ${unitName} && systemctl restart ${unitName}
sleep 2; systemctl is-active ${unitName} || (journalctl -u ${unitName} -n 15 --no-pager; true)`).trim();
  if (!state.startsWith('active')) throw new Error(`${unitName} did not start:\n${state}`);
  console.log(`${app.id.padEnd(16)} service running on 127.0.0.1:${s.port}`);
}

try {
  remote(`mkdir -p ${WEB_ROOT} /var/www/certbot && chown rykersoft:www-data ${WEB_ROOT}`);
  if (!configOnly) {
    for (const app of manifest.apps.filter((a) => ids.length === 0 || ids.includes(a.id))) {
      const built = path.join(here, 'out', app.id);
      if (!fs.existsSync(path.join(built, 'index.html'))) {
        console.log(`${app.id.padEnd(16)} not built, skipped`);
        continue;
      }
      local('rsync', ['-az', '--delete', '-e', `ssh ${SSH.join(' ')}`, `${built}/`, `${HOST}:${WEB_ROOT}/${app.id}/`]);
      remote(`chown -R rykersoft:www-data ${WEB_ROOT}/${app.id} && chmod -R u=rwX,g=rX,o=rX ${WEB_ROOT}/${app.id}`);
      const edition = JSON.parse(fs.readFileSync(path.join(built, 'web-edition.json'), 'utf8'));
      console.log(`${app.id.padEnd(16)} ${edition.version} uploaded`);
      if (app.service) deployService(app);
    }
  }
  writeConfig();
  if (wantCert) {
    const domains = manifest.apps.flatMap((app) => ['-d', hostOf(app)]).join(' ');
    console.log(remote(`certbot certonly --webroot -w /var/www/certbot --cert-name ${CERT_NAME} ${domains} --expand --non-interactive --agree-tos --keep-until-expiring --deploy-hook "systemctl reload nginx" 2>&1 | tail -6`));
    if (!writeConfig()) throw new Error('No certificate was issued. Check that every app address resolves to the VPS.');
  }
} catch (error) {
  fail(String(error.message || error));
}
